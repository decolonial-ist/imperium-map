#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Кабинетские земли Алтая: округ, который принадлежал семье лично.

ЗАЧЕМ (задача куратора 01.09.2026, по своду промышленной колонизации).
Именной указ 12.05.1747, данный Сенату, забрал у наследников Акинфия Демидова
Колывано-Воскресенский, Барнаульский и Шульбинский заводы «со всѣми отведенными
для того землями, съ выкопанными всякими рудами и инструментами, съ пушками и
мѣлкимъ ружьемъ, и съ мастеровыми людьми... и съ приписными крестьянами,
указали Мы взять на Насъ».

«На Насъ» - не в казну государства, а в личное имущество правящей семьи. Так
между Обью и Иртышом возник округ размером с европейское государство, который
полтора века был частной собственностью, а не территорией империи в обычном
смысле. Люди на нём были не подданными государства, а работниками хозяйства.

Что это значило на практике, видно ещё раз в 1899 году: положение Комитета
Сибирской железной дороги о самовольном оставлении переселенцами мест их нового
водворения РАСПРОСТРАНЕНО НА АЛТАЙСКИЙ ОКРУГ (ПСЗ-3, т. XIX, отд. 2, акт
29.06.1899). Крестьянина везли за три тысячи вёрст, сажали на участок частного
владельца и запрещали уходить.

ГЕОМЕТРИЯ ПРИБЛИЗИТЕЛЬНАЯ И ЭТО ЗАПИСАНО В СВОЙСТВАХ. Исторической межи округа
в открытых данных нет. Контур собран как объединение НЫНЕШНИХ Алтайского края и
Республики Алтай (Natural Earth admin-1) - это ядро округа и его нынешний
тёзка. Настоящий округ был больше: он захватывал юг Новосибирской, запад
Кемеровской, юго-восток Томской областей и Рудный Алтай (Змеиногорск, Риддер,
Усть-Каменогорск) в нынешнем Казахстане. Поэтому контур годится, чтобы показать
МЕСТО и МАСШТАБ, и не годится как граница.

НА КАРТЕ ПО УМОЛЧАНИЮ НЕ РИСУЕТСЯ. Правило проекта - только красное и
не-красное; кабинетские земли лежат внутри красного и отдельного цвета не
получают. Слой включается адресом `?kabinet=1` для показа куратору, а строка в
попапе точки идёт всегда.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from shapely.geometry import shape, mapping
from shapely.ops import unary_union
import geoclean as gc

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'cache', 'ne_admin1.geojson')
OUT = os.path.join(ROOT, 'data', 'kabinet', 'kabinet.geojson')

# gn_name у Natural Earth надёжнее name_ru: у Алтайского края в name_ru стоит
# «Республика Алтай» - ошибка самого набора, ловушка при отборе по русскому имени
WANT = {'Altayskiy Kray', 'Respublika Altay'}


def main():
    d = json.load(open(SRC, encoding='utf-8'))
    parts = [shape(f['geometry']) for f in d['features']
             if f['properties'].get('admin') == 'Russia'
             and f['properties'].get('gn_name') in WANT]
    if len(parts) != 2:
        raise SystemExit('ожидались Алтайский край и Республика Алтай, '
                         'найдено %d' % len(parts))
    geom = unary_union(parts).buffer(0)
    fc = {'type': 'FeatureCollection', 'features': [{
        'type': 'Feature',
        'geometry': gc.clean_rings(mapping(geom)),
        'properties': {
            'slug': 'kabinet-altai',
            'name': 'Кабинетские земли Алтая (Алтайский горный округ)',
            'from': '1747-05-12', 'to': '1917-03-15',
            'note': ('взяты из наследства Акинфия Демидова «на Насъ» — в личную '
                     'собственность правящей семьи, а не в казну государства; '
                     'в 1899 году на округ распространили запрет переселенцам '
                     'самовольно уходить с отведённого участка'),
            'source': ('ПСЗРИ I, т. XII, № 9403 (12.05.1747); ПСЗ-3, т. XIX, '
                       'отд. 2 (29.06.1899)'),
            'geometry_note': ('контур приблизительный: объединение нынешних '
                              'Алтайского края и Республики Алтай. Настоящий '
                              'округ был больше — юг Новосибирской, запад '
                              'Кемеровской, юго-восток Томской областей и '
                              'Рудный Алтай в нынешнем Казахстане'),
            'approximate': True,
        },
    }]}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(fc, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False)
    b = geom.bounds
    print('OK %s: bbox %s, %d КБ' % (
        os.path.relpath(OUT, ROOT), [round(v, 2) for v in b],
        os.path.getsize(OUT) // 1024))


if __name__ == '__main__':
    main()
