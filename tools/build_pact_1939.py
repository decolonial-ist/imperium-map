def active(key):
    """Приобретения, действующие на дату среза.

    `until` - день, с которого участок из контура УХОДИТ: западная граница по
    протоколу 04.10.1939 живёт только в окне 17.09.1939-21.06.1941, дальше
    Белосток, Ломжа и левобережье Сана возвращаются Польше и срез 29.06.1945
    их уже не получает.
    """
    day = be.key_date(key)
    return [a for a in ACQ if be.d(a['frm']) <= day
            and (not a.get('until') or day < be.d(a['until']))]


def build(key):
    base_fn, base_txt = BASE[key]
    geom = base_fn()
    added, log = [], []
    for a in active(key):
        g = a['geom']()
        before = geom.area
        geom = unary_union([geom, g]).buffer(0)
        added.append({'name': a['name'], 'id': a['id'], 'from': a['frm'],
                      'until': a.get('until'),
                      'act': a['act'], 'act_full': a['long_act'],
                      'source': a['src'], 'approximate': a['approximate'],
                      'geometry_source': a['geometry_source'],
                      'note': a['note']})
        if geom.area - before > 0.2:
            log.append(f'+ {a["name"]} ({a["frm"]}): '
                       f'{before:.0f} -> {geom.area:.0f} град² '
                       f'(кусок {g.area:.1f})')
    geom = geom.simplify(SIMPLIFY).buffer(0)
    parts = [g for g in (geom.geoms if geom.geom_type == 'MultiPolygon'
                         else [geom]) if g.area > 0.002]
    geom = unary_union(parts)
    props = {
        'name': 'СССР', 'year': key, 'role': 'core',
        'reconstruction': True, 'approximate': True, 'expansion': True,
        'pact1939': True,
        'base': base_txt,
        'added': added,
        'removed': [],
        'source': SOURCE,
    }
    fc = {'type': 'FeatureCollection', 'features': [{
        'type': 'Feature', 'geometry': be._round(mapping(geom)),
        'properties': props}]}
    return fc, log, len(parts)


def write_facts():
    """Слой фактов для попапа истории точки: кто и каким актом взял участок."""
    feats = []
    for a in ACQ:
        g = a.get('fact_geom', a['geom'])().simplify(SIMPLIFY).buffer(0)
        feats.append({'type': 'Feature', 'geometry': be._round(mapping(g)),
                      'properties': {
                          'id': a['id'], 'name': a['name'], 'from': a['frm'],
                          'until': a.get('until'),
                          'act': a['act'], 'act_full': a['long_act'],
                          'source': a['src'], 'note': a['note'],
                          'approximate': a['approximate'],
                          'geometry_source': a['geometry_source'],
                          'pact': PACT}})
    path = os.path.join(DATA, 'pact1939.geojson')
    with open(path, 'w', encoding='utf-8') as f:
        json.dump({'type': 'FeatureCollection', 'features': feats}, f,
                  ensure_ascii=False)
    print(f'OK data/pact1939.geojson: приобретений {len(feats)}, '
          f'{os.path.getsize(path) // 1024} КБ')


def decomposition():
    """Печать разложения разности контуров - это и есть наш пруф геометрии."""
    diff = cs(POST).difference(cs(RIGA)).buffer(0)
    print(f'разность контуров CShapes 18.03.1921 -> 08.05.1945: '
          f'{diff.area:.2f} град²')
    tot = 0.0
    for a in ACQ:
        g = a.get('fact_geom', a['geom'])()
        outside = g.difference(diff).area
        tot += g.area
        tag = (f'  [вне разности контуров: {outside:.2f} град² - западнее '
               f'послевоенной границы]' if outside > 0.05 else '')
        print(f'   {a["frm"]}  {g.area:8.2f}  {a["name"]}{tag}')
    print(f'   сумма кусков {tot:.2f} град² '
          f'(перекрытия на стыках - генерализация источника)')
    rest = diff
    for a in ACQ:
        rest = rest.difference(a.get('fact_geom', a['geom'])())
    rest = clean(rest)
    print(f'   не разобрано: {rest.area:.3f} град²'
          + (f' - куски {[[round(v, 1) for v in p.bounds] for p in (rest.geoms if rest.geom_type == "MultiPolygon" else [rest])][:5]}'
             if not rest.is_empty else ''))


