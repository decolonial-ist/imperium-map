def cs(t):
    return be.cs_core(*t)


def ne(admin, names=None):
    key = (admin, tuple(names) if names else None)
    if key not in _g:
        _g[key] = be.ne_pick(admin, names)
    return _g[key]


def clean(g):
    """Убрать заусенцы генерализации: куски мельче SPECK."""
    g = g.buffer(0)
    parts = [p for p in (g.geoms if g.geom_type == 'MultiPolygon' else [g])
             if p.area >= SPECK]
    return unary_union(parts) if parts else g


def geom_1939():
    """Западная Украина и Западная Беларусь: остаток разности контуров."""
    if '39' in _g:
        return _g['39']
    diff = cs(POST).difference(cs(RIGA)).buffer(0)
    reserved = unary_union([ne(a, n) for a, n in RESERVED]).buffer(0)
    # ядро куска - целиком современные области (так между ним и основой среза
    # не остаётся щели: основа 1922 г. оцифрована с медианой ~30 км и местами
    # уходит восточнее линии Риги)
    core = cs(POST).intersection(unary_union([ne('Belarus', WEST_BY),
                                              ne('Ukraine', WEST_UA)]))
    # плюс западные кромки соседних областей - только сама разность
    edge = diff.intersection(unary_union([ne('Ukraine', EDGE_UA),
                                          ne('Poland', EDGE_PL)]))
    rest = diff.difference(reserved)          # то, что не отдано другим датам
    _g['39'] = clean(unary_union([core, edge, rest]))
    return _g['39']


def geom_1939_fact():
    """То же, но обрезанное самой разностью контуров.

    Для ПОКАЗА кусок берётся целыми областями: основа среза 17.09.1939 -
    оцифровка атласа с медианой ~30 км, и если резать по линии Риги, между
    основой и куском остаются щели (проверено: две дырки 0.073 и 0.027 град²).
    Для ПОПАПА так нельзя: целая Гомельская область накрыла бы Гомель, целая
    Витебская - Витебск, и попап написал бы, что они «в империи с 17.09.1939»,
    хотя они в ней с XVIII века. Поэтому в слой фактов идёт обрезанная версия.
    """
    if '39f' not in _g:
        diff = cs(POST).difference(cs(RIGA)).buffer(0)
        _g['39f'] = clean(geom_1939().intersection(diff))
    return _g['39f']


def geom_vilnius():
    """Виленский край: часть Литвы, которой у контура источника 1940 г. нет."""
    if 'vln' not in _g:
        _g['vln'] = clean(cs(POST).intersection(ne('Lithuania', None))
                          .difference(cs(BALTIC)))
    return _g['vln']


def atlas_1922():
    """Основа среза 17.09.1939: оцифровка атласа, объединённая с контуром Риги.

    26.08.2026, по жалобе куратора («якась хуйня в Украине в 1939, прорезь»):
    одна оцифровка атласа даёт щель вдоль старой советско-польской границы.
    Её медиана ~30 км, и у Шепетовки, Славуты и Изяслава линия уходит
    ВОСТОЧНЕЕ городов - они выпадали из контура, а новый кусок 1939 года их не
    накрывает (это Хмельницкая область, советская и до 1939). Между основой и
    куском оставалась чёрная прорезь ~2 град².

    Лечение: объединяем атлас с контуром CShapes на линии Риги (он точен, но
    ошибочно включает Танну-Туву - она независима до 1944) и вычитаем Туву.
    """
    if 'at' not in _g:
        with open(os.path.join(DATA, 'years', '1922.geojson'),
                  encoding='utf-8') as f:
            fc = json.load(f)
        atlas = unary_union([shape(x['geometry']).buffer(0)
                             for x in fc['features']]).buffer(0)
        with open(os.path.join(bd.CACHE, 'tuva_ne10m.geojson'),
                  encoding='utf-8') as f:
            tuva = unary_union([shape(x['geometry']).buffer(0)
                                for x in json.load(f)['features']]).buffer(0)
        _g['at'] = unary_union([atlas, cs(RIGA)]).difference(
            tuva.buffer(0.02)).buffer(0)
    return _g['at']


