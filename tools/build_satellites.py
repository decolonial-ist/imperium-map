#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сателлиты империи: земля, где на месте распоряжается не она сама, а свои
люди на её деньгах и оружии (задание куратора 08.09.2026).

ЗАЧЕМ. Беларусь с 1991 года карта красит отдельным слоем: красная гамма, но
пунктиром - сателлит, а не территория. Тем же приёмом решено показывать Чечню
1993-1994 годов: куратор 08.09.2026 на вопрос «красить ли контроль местной
промосковской оппозиции» - «крась как современную беларусь, зона влияния».

ЧТО ЗДЕСЬ. Заявка домена Нохчи от 08.09.2026 с документами
(NOTICE_OT_NOHCHI_CHECHNYA_1993-1994_KONTROL_2026-09-08.md, таблица точек
chechnya_1991_1994_opposition_control_from_nohchi.csv). Суть: с 16.12.1993 в
Надтеречном районе сидит «Временный совет Чеченской Республики» Умара
Автурханова, который Москва финансирует, вооружает и признаёт законной властью;
летом 1994 к нему прибавляются Урус-Мартан и Гехи (Гантамиров), Толстой-Юрт
(группа Хасбулатова), Ищёрская, Аргун (отряд Лабазанова). Российской армии на
земле ещё нет: экипажи с 02.09.1994, вторжение 11.12.1994 - дальше слой войны.

ЧЕГО ЗДЕСЬ НЕТ. Окно 01.11.1991-15.12.1993, когда Надтеречный район просто не
подчинялся Грозному: это ещё не Москва на земле, а местное неподчинение, и
решения куратора по нему нет.

ПЛОЩАДЬ ТОЛЬКО ТАМ, ГДЕ ОНА БЫЛА. Куратор 09.09.2026 о кружках вокруг сёл:
«ты хочешь сказать, что в этих кружках была подконтрольная зона? как оно
возникало в окружении чеченцев?» - и велел копать фактаж. Розыск по первичке:
- «Мемориал» 2010: после срыва референдума 05.06.1993 вооружённые сторонники
  оппозиции «отступили в Надтеречный и Урус-Мартановский районы Чечни»; её
  «оплотами стали Надтеречный и Урус-Мартановский районы», а прочие места -
  «многие населённые пункты плоскостной Чечни»;
- Дунлоп 1998 (по М. Эйсмонт): 25.08.1994 правительство России секретным
  постановлением признало Временный совет «единственной законной властью в
  Чечне» и усилило выплаты зарплат и пенсий населению обоих районов; Хасбулатов
  о лете 1994: «практически весь юго-западный край республики - Урус-Мартановский
  район - открыто против режима».
Поэтому ПОЛИГОНАМИ идут два района, у которых была своя администрация на своей
территории, а прочие места - ТОЧКАМИ без всякого радиуса, как остроги: там
стояли отряды, но площади за ними нет.

Запуск: cd ~/tmp/imperium-map && .venv/bin/python3 tools/build_satellites.py
На выходе data/satellite/chechnya_1993_1994.geojson.
"""
import json
import os

from shapely.geometry import mapping, shape
from shapely.ops import unary_union

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'data')
OUT = os.path.join(DATA, 'satellite')
SRC_NOTICE = 'заявка домена Нохчи 08.09.2026 с документами: NOTICE_OT_NOHCHI_CHECHNYA_1993-1994_KONTROL_2026-09-08.md'
END = '1994-12-10'          # 11.12.1994 входит российская армия - дальше слой войны

# районы-оплоты: файл контура, имя, с какой даты, чем держались
AREAS = [
    ('opposition_1993_1994.geojson', 'Надтеречный район', '1993-12-16',
     'Временный совет Чеченской Республики (Умар Автурханов)',
     '16.12.1993 в Знаменском создан Временный совет; Москва его финансирует '
     '(1,5 млрд рублей наличными 30.07.1994), вооружает (танки и бронетранспортёры '
     'из Моздока, август 1994) и 25.08.1994 секретным постановлением признаёт '
     '«единственной законной властью в Чечне»'),
    ('urus_martan_1994.geojson', 'Урус-Мартановский район', '1994-08-25',
     'отряды Беслана Гантамирова',
     'второй оплот Временного совета: 25.08.1994 правительство России признало '
     'совет законной властью и стало платить зарплаты и пенсии населению '
     'Надтеречного и Урус-Мартановского районов (Дунлоп 1998 по М. Эйсмонт); '
     'Хасбулатов о том же лете: «практически весь юго-западный край республики - '
     'Урус-Мартановский район - открыто против режима»'),
]

# ТОЧКИ УБРАНЫ 09.09.2026. Ищёрская, Толстой-Юрт и Аргун - места, где стоял
# отряд оппозиции, но площади за ними нет, а источник даёт только упоминание
# («многие населённые пункты плоскостной Чечни»), без границ и в большинстве
# случаев без даты перехода. На карте, где красное означает управление
# территорией, точка без территории читается как место власти и вдобавок
# сливается с точками острогов - куратор 09.09.2026: «что за точки возникают?».
# Сами эпизоды остаются в базе домена Нохчи: Аргун под отрядом Лабазанова до
# 05.09.1994, Толстой-Юрт под группой Хасбулатова 20.08-16.09.1994, Ищёрская
# летом 1994. Вернуть их на карту - отдельное решение куратора.
POINTS_OFF = [
    ('Ищёрская', 43.714, 45.129, '1994-07-01', END,
     'станица на левом берегу Терека; 06.08.1994 пост оппозиции на Ищерском мосту'),
    ('Толстой-Юрт', 43.442, 45.775, '1994-08-20', '1994-09-16',
     'группа Руслана Хасбулатова с бронетехникой; 17.09.1994 село взято силами Грозного'),
    ('Аргун', 43.295, 45.869, '1994-06-20', '1994-09-04',
     'отряд Руслана Лабазанова, союзника Автурханова; 05.09.1994 разгромлен, город снова под Грозным'),
]


def main():
    feats = []
    for fname, name, frm, holder, why in AREAS:
        src = os.path.join(DATA, 'chechnya', fname)
        if not os.path.exists(src):
            raise SystemExit('нет %s - сперва .venv/bin/python3 tools/fetch_osm_units.py '
                             'chechnya_opposition_1994 и chechnya_urus_martan_1994' % src)
        with open(src, encoding='utf-8') as f:
            d = json.load(f)
        g = unary_union([shape(x['geometry']).buffer(0) for x in d['features']])
        if g.is_empty:
            raise SystemExit('контур %s пуст' % name)
        feats.append({'type': 'Feature', 'geometry': mapping(g), 'properties': {
            'name': name, 'kind': 'area', 'holder': holder,
            'from': frm, 'to': END, 'why': why,
            'source': SRC_NOTICE + '; контур - OpenStreetMap'}})

    for name, lat, lon, frm, to, why in []:
        feats.append({'type': 'Feature',
                      'geometry': {'type': 'Point', 'coordinates': [lon, lat]},
                      'properties': {'name': name, 'kind': 'point',
                                     'holder': 'отряд промосковской оппозиции',
                                     'from': frm, 'to': to, 'why': why,
                                     'note': 'площади за этим местом нет - только отряд в самом селе',
                                     'source': SRC_NOTICE}})

    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, 'chechnya_1993_1994.geojson')
    with open(path, 'w', encoding='utf-8') as f:
        json.dump({'type': 'FeatureCollection', 'features': feats}, f,
                  ensure_ascii=False, separators=(',', ':'))
    print('OK %s: фич %d (%.0f КБ)' % (path, len(feats), os.path.getsize(path) / 1024))
    for x in feats:
        p = x['properties']
        print('   %-24s %-6s %s .. %s' % (p['name'], p['kind'], p['from'], p['to']))


if __name__ == '__main__':
    main()
