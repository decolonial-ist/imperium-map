def _add_west_keys():
    own = {s['key'] for s in SLICES}
    base_slices = sorted(SLICES, key=lambda s: s['key'])
    for key, note, anchor in WEST_KEYS:
        if key in own:
            raise SystemExit(f'WEST_KEYS: срез {key} уже есть в SLICES')
        prev = [s for s in base_slices if s['key'] < key]
        if not prev:
            raise SystemExit(f'WEST_KEYS: {key} раньше первого среза окна')
        SLICES.append(dict(key=key, minus=list(prev[-1].get('minus', [])),
                           note=note, anchor=anchor, west=True))


_add_west_keys()


