def fetch(name, region):
    q = f'{name} {region}'
    url = API + '?' + urllib.parse.urlencode(
        {'q': q, 'format': 'json', 'polygon_geojson': 1, 'limit': 1})
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=60) as f:
        data = json.load(f)
    if not data:
        raise SystemExit(f'Nominatim не нашёл: {q}')
    it = data[0]
    if it.get('class') != 'boundary':
        raise SystemExit(f'{q}: пришло не административное деление, '
                         f'а {it.get("class")}/{it.get("type")}')
    return it['geojson'], it['display_name'], it.get('osm_id')


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in GROUPS:
        print('группы:')
        for k, g in GROUPS.items():
            print(f'  {k:12} {g["label"]} ({len(g["units"])} единиц)')
        return 0
    key = sys.argv[1]
    g = GROUPS[key]
    from shapely.geometry import shape, mapping
    from shapely.ops import unary_union
    parts, prov = [], []
    for name, region in g['units']:
        geom, disp, osm_id = fetch(name, region)
        parts.append(shape(geom).buffer(0))
        prov.append({'name': name, 'region': region,
                     'osm_id': osm_id, 'display_name': disp})
        print(f'   + {name} ({region})')
        time.sleep(1.1)
    union = unary_union(parts)
    out = os.path.join(DATA, g['out'])
    os.makedirs(os.path.dirname(out), exist_ok=True)
    fc = {'type': 'FeatureCollection', 'features': [{
        'type': 'Feature',
        'geometry': mapping(union),
        'properties': {
            'name': g['label'],
            'source': 'OpenStreetMap через Nominatim (polygon_geojson), '
                      'выгрузка tools/fetch_ua_units.py',
            'units': prov,
            'approximate': True,
            'note': 'районы 2020 года — ПРИБЛИЖЕНИЕ исторической земли, '
                    'а не её граница из документа',
        }}]}
    with open(out, 'w', encoding='utf-8') as f:
        json.dump(fc, f, ensure_ascii=False)
    print(f'OK {g["out"]}: единиц {len(prov)}, '
          f'{os.path.getsize(out) // 1024} КБ')
    return 0


if __name__ == '__main__':
    sys.exit(main())
